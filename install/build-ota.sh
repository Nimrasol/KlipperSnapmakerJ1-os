#!/bin/bash
# Build and sign the OTA package that installs KlipperSnapmakerJ1-os through
# the stock recovery.
#
# Copyright (C) 2026  Nimrasol
#
# This file may be distributed under the terms of the GNU GPLv3 license.
#
# Usage: install/build-ota.sh LK2ND LINUX_BOOT OUT_ZIP
#   LK2ND       lk2nd.img (boot partition image)
#   LINUX_BOOT  linux-boot.img built in install mode (cache partition image)
#   OUT_ZIP     signed OTA package to write
#
# The images are NOT put into the package (it stays small); the package only
# carries the update-binary, which reads the images from the USB stick and
# checks them against the sha256 compiled in here.  The package is signed
# with the public AOSP test key, which the stock recovery trusts.
#
# Requirements: arm-linux-gnueabihf-gcc, java, curl, zip.
set -e

HERE="$(cd "$(dirname "$0")" && pwd)"
LK2ND="$(realpath "$1")"
LINUX_BOOT="$(realpath "$2")"
OUT="$(realpath -m "$3")"
WORK="${TMPDIR:-/tmp}/j1-ota.$$"
CACHE="${XDG_CACHE_HOME:-$HOME/.cache}/j1-ota"

if [ ! -f "$LK2ND" ] || [ ! -f "$LINUX_BOOT" ] || [ -z "$3" ]; then
    sed -n '8,12p' "$0"
    exit 1
fi
mkdir -p "$WORK" "$CACHE"
trap 'rm -rf "$WORK"' EXIT

# -- the public AOSP test key and the AOSP whole-file signer ----------------
TAG=android-7.1.2_r39
gfetch() {  # gfetch REPO PATH OUTFILE   (googlesource base64 download)
    [ -s "$CACHE/$3" ] && return 0
    echo "fetch $3"
    curl -fsSL "https://android.googlesource.com/platform/$1/+/refs/tags/$TAG/$2?format=TEXT" \
        | base64 -d > "$CACHE/$3"
}
gfetch build target/product/security/testkey.x509.pem testkey.x509.pem
gfetch build target/product/security/testkey.pk8 testkey.pk8
# signapk from 6.0.1: bundles bouncycastle, no conscrypt native dependency;
# the whole-file OTA format it emits is the one the recovery expects.
if [ ! -s "$CACHE/signapk.jar" ]; then
    echo "fetch signapk.jar"
    curl -fsSL "https://android.googlesource.com/platform/prebuilts/sdk/+/refs/tags/android-6.0.1_r81/tools/lib/signapk.jar?format=TEXT" \
        | base64 -d > "$CACHE/signapk.jar"
fi

# -- generated digests.h ----------------------------------------------------
gen_digest() {  # gen_digest NAME FILE
    local hex
    hex=$(sha256sum "$2" | cut -d' ' -f1)
    printf 'static const unsigned char %s[32] = {' "$1"
    echo "$hex" | sed -E 's/(..)/0x\1,/g'
    printf '};\n'
}
{
    echo "/* generated by build-ota.sh - do not edit */"
    echo "#ifndef DIGESTS_H"
    echo "#define DIGESTS_H"
    gen_digest SHA256_LK2ND "$LK2ND"
    gen_digest SHA256_LINUX_BOOT "$LINUX_BOOT"
    echo "#endif"
} > "$WORK/digests.h"

# -- compile the update-binary (static ARM) ---------------------------------
echo "== compile update-binary (static armhf)"
arm-linux-gnueabihf-gcc -static -Os -Wall -Wextra \
    -I"$HERE" -I"$WORK" \
    "$HERE/update-binary.c" "$HERE/sha256.c" \
    -o "$WORK/update-binary"
arm-linux-gnueabihf-strip "$WORK/update-binary"
file "$WORK/update-binary"

# -- assemble the OTA zip ---------------------------------------------------
echo "== assemble package"
PKG="$WORK/pkg"
mkdir -p "$PKG/META-INF/com/google/android" "$PKG/META-INF/com/android"
cp "$WORK/update-binary" "$PKG/META-INF/com/google/android/update-binary"
cat > "$PKG/META-INF/com/android/metadata" <<EOF
ota-type=BLOCK
post-timestamp=$(date +%s)
pre-device=sc20w
EOF
UNSIGNED="$WORK/unsigned.zip"
( cd "$PKG" && zip -q -r -X "$UNSIGNED" . )

echo "== sign (public AOSP test key, whole-file)"
mkdir -p "$(dirname "$OUT")"
java -Xmx512m -jar "$CACHE/signapk.jar" \
    -w "$CACHE/testkey.x509.pem" "$CACHE/testkey.pk8" "$UNSIGNED" "$OUT"
echo "OTA: $OUT ($(stat -c %s "$OUT") bytes)"
